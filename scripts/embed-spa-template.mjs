// After both builds: embeds frontend/dist/index.html into backend/dist/spaTemplate.js,
// so the API function can serve pre-rendered pages (see backend/src/routes/seo.ts).
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(new URL('../frontend/dist/index.html', import.meta.url), 'utf8');
if (!html.includes('<div id="root"></div>')) {
  throw new Error('frontend/dist/index.html has no empty #root');
}
writeFileSync(
  new URL('../backend/dist/spaTemplate.js', import.meta.url),
  `// Generated by scripts/embed-spa-template.mjs\nexport default ${JSON.stringify(html)};\n`,
);
console.log(`Embedded SPA template (${html.length} chars).`);
